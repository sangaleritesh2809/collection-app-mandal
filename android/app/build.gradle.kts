    }

    aaptOptions {
        ignoreAssetsPattern = "!.svn:!.git:!.ds_store:!*.scc:.*:<dir>_*:!CVS:!thumbs.db:!picasa.ini:!*~:!desktop.ini:!*.ini"
    }

    packaging {
        resources {
            excludes += listOf("/META-INF/{AL2.0,LGPL2.1}")
        }
        jniLibs {
            pickFirsts += listOf("**/*.so")
        }
    }
}

tasks.configureEach {
    if (name.contains("cleanMergeReleaseAssets") || (name.startsWith("cleanMerge") && name.endsWith("Assets"))) {
        enabled = false
    }
    if (name.contains("mergeReleaseNativeLibs")) {
        doFirst {
            file("${project.layout.buildDirectory.get()}/intermediates/merged_native_libs").deleteRecursively()
        }
    }
}

